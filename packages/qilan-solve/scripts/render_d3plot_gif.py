import argparse
import json
import os
import subprocess
import shutil
import sys
import tempfile
from pathlib import Path
import locale


def find_hyperview():
    """
    Find HyperView executable in common installation paths.
    
    Checks:
    1. HYPERWORKS_HOME environment variable
    2. Common Altair installation paths
    3. System PATH
    
    Returns:
        str or None: Path to hw.exe if found
    """
    # Check HYPERWORKS_HOME environment variable first
    hyperworks_home = os.getenv('HYPERWORKS_HOME')
    if hyperworks_home:
        hw_exe = os.path.join(hyperworks_home, 'hwdesktop', 'hw', 'bin', 'win64', 'hw.exe')
        if os.path.isfile(hw_exe):
            return hw_exe
        # Try alternative structure
        hw_exe = os.path.join(hyperworks_home, 'hw', 'bin', 'win64', 'hw.exe')
        if os.path.isfile(hw_exe):
            return hw_exe
    
    for root in [Path(r'C:\Program Files\Altair'), Path(r'D:\Program Files\Altair')]:
        if root.is_dir():
            for version in sorted(root.iterdir(), key=lambda p: p.name, reverse=True):
                candidate = version / 'hwdesktop' / 'hw' / 'bin' / 'win64' / 'hw.exe'
                if candidate.is_file():
                    return str(candidate)

    for exe_name in ["hw.exe", "hyperview.exe"]:
        found = shutil.which(exe_name)
        if found:
            return found
    
    return None


def create_tcl_script(d3plot_path, output_gif, temp_dir):
    """Create TCL script for HyperView to render GIF animation."""
    # Normalize paths for TCL
    d3plot_unix = d3plot_path.replace('\\', '/')
    gif_unix = output_gif.replace('\\', '/')
    
    tcl_content = f'''# HyperView TCL script for d3plot GIF rendering
# Generated by render_d3plot_gif.py

# Load d3plot file
set filename "{d3plot_unix}"
*fReadFile $filename 1 0

# Set up animation
*createmark models 1 1
*animate modal 1 1 1

# Set view to isometric
*view iso1
*viewfit

# Set contour to displacement  
*post1()

# Export as animated GIF
set output_gif "{gif_unix}"
*writegif $output_gif 0 0 800 600 1

# Exit
*quit
'''
    
    tcl_path = os.path.join(temp_dir, "render_d3plot.tcl")
    with open(tcl_path, 'w') as f:
        f.write(tcl_content)
    
    return tcl_path


def render_d3plot_gif(d3plot_path, output_gif, hyperview_exe=None):
    """
    Render d3plot to GIF using HyperView.
    
    Args:
        d3plot_path: Path to d3plot file
        output_gif: Output GIF path
        hyperview_exe: Optional HyperView executable path
    
    Returns:
        dict: Result with ok status and message
    """
    # Find HyperView
    if not hyperview_exe:
        hyperview_exe = find_hyperview()
    
    if not hyperview_exe or not os.path.exists(hyperview_exe):
        return {
            'ok': False,
            'error': (
                'HyperView not found. Please ensure:\n'
                '1. Altair HyperWorks with HyperView is installed, AND\n'
                '2. Configure the Altair HyperWorks version directory in application settings\n'
                '   or set HYPERWORKS_HOME, or specify --hyperview when running this script\n'
                '\n'
                'Example: set HYPERWORKS_HOME=C:\\Program Files\\Altair\\2025'
            ),
            'hyperview': hyperview_exe
        }
    
    # Check d3plot exists
    if not os.path.exists(d3plot_path):
        return {
            'ok': False,
            'error': f'd3plot file not found: {d3plot_path}'
        }
    
    # Create temp directory for TCL script
    with tempfile.TemporaryDirectory() as temp_dir:
        try:
            # Create TCL script
            tcl_script = create_tcl_script(d3plot_path, output_gif, temp_dir)
            
            # Run HyperView with TCL script
            cmd = [hyperview_exe, "-tcl", tcl_script]
            
            print(f"Running HyperView: {' '.join(cmd)}", file=sys.stderr)
            
            result = subprocess.run(
                cmd,
                capture_output=True,
                encoding='utf-8' if sys.platform != "win32" else 'gbk',
                errors='replace',
                timeout=600,
                cwd=os.path.dirname(d3plot_path)
            )
            
            # Check if GIF was created
            if os.path.exists(output_gif):
                file_size = os.path.getsize(output_gif)
                return {
                    'ok': True,
                    'message': f'GIF rendered successfully: {output_gif}',
                    'gif_path': output_gif,
                    'size_bytes': file_size,
                    'hyperview': hyperview_exe
                }
            else:
                return {
                    'ok': False,
                    'error': 'HyperView did not generate GIF file',
                    'stdout': result.stdout,
                    'stderr': result.stderr,
                    'returncode': result.returncode
                }
        
        except subprocess.TimeoutExpired:
            return {
                'ok': False,
                'error': 'HyperView rendering timed out (10 minutes)'
            }
        except Exception as e:
            return {
                'ok': False,
                'error': f'Failed to render GIF: {str(e)}'
            }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--d3plot', required=True, help='Path to d3plot file')
    parser.add_argument('--output', required=True, help='Output GIF path')
    parser.add_argument('--hyperview', default=None, help='HyperView executable path')
    args = parser.parse_args()
    
    result = render_d3plot_gif(args.d3plot, args.output, args.hyperview)
    
    print(json.dumps(result, indent=2))
    
    if not result['ok']:
        sys.exit(1)


if __name__ == '__main__':
    main()
