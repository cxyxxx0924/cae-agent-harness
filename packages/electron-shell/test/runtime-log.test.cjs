const assert = require('node:assert/strict')
const { EventEmitter } = require('node:events')
const { mkdtemp, readFile, rm, writeFile } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { PassThrough } = require('node:stream')
const { test } = require('node:test')
const { RuntimeLog } = require('../dist/runtime-log.js')

test('persistent diagnostics redact credentials even when pipe chunks split the secret', async t => {
  const root = await mkdtemp(join(tmpdir(), 'cae-runtime-log-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  const file = join(root, 'logs', 'startup.log')
  const log = new RuntimeLog(file)
  log.setSecrets(['sk-test-private', 'solver-private'])
  const proc = Object.assign(new EventEmitter(), { stdout: new PassThrough(), stderr: new PassThrough() })
  log.capture(proc)
  proc.stdout.write('dsh web: http://127.0.0.1:3080/?tok')
  proc.stdout.write('en=launch-private\n')
  proc.stderr.write('API key: sk-test-')
  proc.stderr.end('private; service: solver-private\n')
  log.setSecrets(['new-key'])
  log.write('main', 'old key sk-test-private; new key new-key')
  const text = await readFile(file, 'utf8')
  const failure = log.failure(new Error('Failed with sk-test-private'))
  for (const value of ['sk-test-private', 'solver-private', 'launch-private', 'new-key']) {
    assert.equal(text.includes(value), false)
    assert.equal(failure.includes(value), false)
  }
  assert.match(text, /\[dsh:stdout\] dsh web:/)
  assert.match(text, /\?token=\[REDACTED\]/)
  assert.match(failure, /startup\.log/)
  assert.match(failure, /最近的后台输出/)
})

test('runtime logs rotate before growing beyond the size limit', async t => {
  const root = await mkdtemp(join(tmpdir(), 'cae-runtime-rotation-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  const file = join(root, 'startup.log')
  await writeFile(file, 'x'.repeat(2 * 1024 * 1024 + 1))
  const log = new RuntimeLog(file)
  log.write('main', 'new startup')
  assert.match(await readFile(file, 'utf8'), /new startup/)
  assert.equal((await readFile(`${file}.previous`, 'utf8')).length, 2 * 1024 * 1024 + 1)
})
