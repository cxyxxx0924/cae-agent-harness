const assert = require('node:assert/strict')
const fs = require('node:fs')
const { join } = require('node:path')
const { tmpdir } = require('node:os')
const { test } = require('node:test')
const { WorkflowStore, STAGES } = require('../../cae-workflow/state.cjs')
const { workflowArtifact, workflowPreview, workflowField } = require('../dist/workflow.js')

test('desktop workflow file APIs are restricted to validated artifacts of the current conversation', t => {
  const directory = fs.mkdtempSync(join(tmpdir(), 'cae-desktop-workflow-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const store = new WorkflowStore(join(directory, 'state'))
  store.create('session')
  const image = join(directory, 'preview.png'); fs.writeFileSync(image, Buffer.from('89504e470d0a1a0a', 'hex'))
  const remote = 'Z:\\service-only\\d3plot'
  store.change('session', undefined, state => { state.stages[0].artifacts = [{ role: 'preview', path: image, remote: false }, { role: 'd3plot', path: remote, remote: true }]; return state })
  assert.equal(workflowArtifact(store, 'session', image), image)
  assert.match(workflowPreview(store, 'session', image), /^data:image\/png;base64,/)
  assert.throws(() => workflowArtifact(store, 'other-session', image), /当前对话/)
  assert.throws(() => workflowArtifact(store, 'session', remote), /本机产物/)
  assert.throws(() => workflowArtifact(store, 'session', join(directory, 'unverified.png')), /已经验证/)
  assert.equal(workflowField(store, 'session', 'igs_file', STAGES).type, 'file')
  assert.throws(() => workflowField(store, 'session', 'not-a-field', STAGES), /不支持/)
  store.change('session', undefined, state => { state.status = 'running'; return state })
  assert.throws(() => workflowField(store, 'session', 'igs_file', STAGES), /不支持/)
})
